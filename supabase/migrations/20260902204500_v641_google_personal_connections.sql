create or replace function public.uon_google_disconnect(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, vault, pg_temp
as $$
declare
  v_role text := coalesce(current_setting('request.jwt.claim.role', true), '');
  v_access_id uuid;
  v_refresh_id uuid;
begin
  if v_role <> 'service_role' then
    raise exception 'service_role_required' using errcode = '42501';
  end if;
  select token_secret_id, refresh_secret_id into v_access_id, v_refresh_id
  from public.uon_google_connections where user_id = p_user_id;
  if v_access_id is not null then delete from vault.secrets where id = v_access_id; end if;
  if v_refresh_id is not null then delete from vault.secrets where id = v_refresh_id; end if;
  update public.uon_google_connections set
    status = 'revoked', granted_scopes = '{}'::text[],
    calendar_read_enabled = false, drive_file_enabled = false,
    token_secret_id = null, refresh_secret_id = null, token_expires_at = null,
    revoked_at = now(), updated_at = now()
  where user_id = p_user_id;
  insert into public.uon_google_connection_audit(user_id, action)
  values (p_user_id, 'disconnected');
end;
$$;

